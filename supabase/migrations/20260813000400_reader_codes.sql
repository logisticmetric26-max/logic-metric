create table if not exists public.reader_codes (
  id                uuid primary key default gen_random_uuid(),
  ppu               text not null,
  internal_number   text not null,
  reader_code       text not null,
  reader_type       text,
  active            boolean not null default true,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  created_by        uuid references auth.users (id) on delete set null,
  updated_by        uuid references auth.users (id) on delete set null,

  constraint reader_codes_ppu_format check (ppu ~ '^[A-Z0-9]{4,10}$'),
  constraint reader_codes_internal_number_format check (internal_number ~ '^[A-Z0-9][A-Z0-9 _-]{0,19}$'),
  constraint reader_codes_reader_code_format check (reader_code ~ '^[A-Z0-9][A-Z0-9 _-]{0,39}$'),
  constraint reader_codes_reader_type_format check (
    reader_type is null or reader_type ~ '^[A-Z0-9][A-Z0-9 _-]{0,39}$'
  )
);

