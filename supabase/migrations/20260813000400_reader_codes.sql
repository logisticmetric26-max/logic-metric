create or replace function app.normalize_reader_code_record()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.ppu := app.normalize_ppu(new.ppu);
  new.internal_number := app.normalize_code(new.internal_number);
  new.reader_code := app.normalize_code(new.reader_code);
  new.reader_type := app.normalize_code(new.reader_type);

  if new.ppu is null then
    raise exception 'PPU_REQUIRED' using errcode = '23514';
  end if;

  if new.internal_number is null then
    raise exception 'INTERNAL_NUMBER_REQUIRED' using errcode = '23514';
  end if;

  if new.reader_code is null then
    raise exception 'READER_CODE_REQUIRED' using errcode = '23514';
  end if;

  return new;
end;
$$;

