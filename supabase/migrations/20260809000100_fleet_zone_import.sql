alter table public.fleet
  add column if not exists zone text;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'fleet_zone_check'
      and conrelid = 'public.fleet'::regclass
  ) then
    alter table public.fleet
      add constraint fleet_zone_check
      check (zone is null or length(trim(zone)) between 1 and 120);
  end if;
end
$$;

comment on column public.fleet.zone is
  'Operational zone assigned to the bus in the imported fleet snapshot.';

create index if not exists fleet_zone_idx
  on public.fleet (zone)
  where zone is not null;

create index if not exists fleet_terminal_zone_idx
  on public.fleet (terminal_id, zone)
  where zone is not null;

create or replace function app.normalize_fleet_row()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.ppu := app.normalize_ppu(new.ppu);
  new.internal_number := app.normalize_code(new.internal_number);
  new.model := nullif(trim(coalesce(new.model, '')), '');
  new.subclass := nullif(trim(coalesce(new.subclass, '')), '');
  new.zone := nullif(regexp_replace(trim(coalesce(new.zone, '')), '\s+', ' ', 'g'), '');

  if new.ppu is null then
    raise exception 'PPU_REQUIRED' using errcode = '23514';
  end if;

  if new.internal_number is null then
    raise exception 'INTERNAL_NUMBER_REQUIRED' using errcode = '23514';
  end if;

  return new;
end;
$$;

create or replace view public.fleet_expiration_status
with (security_invoker = on) as
select
  f.id                          as fleet_id,
  f.internal_number,
  f.ppu,
  f.model,
  f.subclass,
  f.fuel_type,
  f.terminal_id,
  f.active,
  la.id                         as last_approved_event_id,
  la.expiration_date,
  la.return_at                  as last_approved_at,
  la.guide_number               as last_guide_number,
  case
    when la.expiration_date is null then 'NO_RECORD'
    when la.expiration_date < app.today_local() then 'EXPIRED'
    when la.expiration_date <= app.today_local() + app.expiring_soon_days() then 'EXPIRING_SOON'
    else 'VALID'
  end                           as expiration_status,
  (la.expiration_date - app.today_local()) as days_to_expiration,
  f.zone
from public.fleet f
left join lateral (
  select e.id, e.expiration_date, e.return_at, e.guide_number
  from public.technical_review_events e
  where e.fleet_id = f.id
    and e.status = 'CLOSED'
    and e.result = 'APPROVED'
  order by e.return_at desc, e.created_at desc
  limit 1
) la on true;

create or replace view public.fleet_view
with (security_invoker = on) as
select
  f.id,
  f.internal_number,
  f.ppu,
  f.model,
  f.subclass,
  f.fuel_type,
  ft.label        as fuel_type_label,
  f.terminal_id,
  t.name          as terminal_name,
  f.active,
  f.created_at,
  f.updated_at,
  f.zone
from public.fleet f
join public.terminals t on t.id = f.terminal_id
left join public.fleet_fuel_types ft on ft.code = f.fuel_type;

