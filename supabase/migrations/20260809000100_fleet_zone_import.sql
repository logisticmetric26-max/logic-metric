set terminal_name = 'Terminal Redvan'
where terminal_name is null
  and zone = 'REDVAN';

do $$
begin
  if exists (select 1 from tmp_fleet_import where zone is null) then
    raise exception 'FLEET_IMPORT_ZONE_REQUIRED';
  end if;

  if exists (select 1 from tmp_fleet_import where terminal_name is null) then
    raise exception 'FLEET_IMPORT_TERMINAL_REQUIRED';
  end if;

  if exists (select 1 from tmp_fleet_import where fuel_type not in ('DIESEL', 'ELECTRIC')) then
    raise exception 'FLEET_IMPORT_UNKNOWN_FUEL_TYPE';
  end if;

  if exists (select ppu from tmp_fleet_import group by ppu having count(*) > 1) then
    raise exception 'FLEET_IMPORT_DUPLICATE_PPU';
  end if;

  if exists (
    select internal_number
    from tmp_fleet_import
    group by internal_number
    having count(*) > 1
  ) then
    raise exception 'FLEET_IMPORT_DUPLICATE_INTERNAL_NUMBER';
  end if;
end
$$;

