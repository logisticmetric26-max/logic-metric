create temporary table tmp_review_history_actor (
  actor_id uuid not null
) on commit drop;

insert into tmp_review_history_actor (actor_id)
select p.id
from public.profiles p
where p.status = 'ACTIVE'
order by p.has_global_access desc, p.created_at asc
limit 1;

do $$
begin
  if not exists (select 1 from tmp_review_history_actor) then
    raise exception 'TECH_REVIEW_HISTORY_IMPORT_REQUIRES_ACTIVE_PROFILE';
  end if;
end
$$;

create temporary table tmp_review_history_resolved on commit drop as
with normalized as (
  select
    i.source_row,
    app.normalize_code(i.internal_number) as internal_number,
    app.normalize_ppu(i.ppu)              as ppu,
    case
      when lower(trim(i.result_label)) = 'aprobado' then 'APPROVED'
      when lower(trim(i.result_label)) = 'rechazado' then 'REJECTED'
      else null
    end                                   as result_code,
    app.normalize_code(i.guide_number)    as guide_number,
    to_date(trim(i.expiration_text), 'DD-MM-YYYY')
                                           as effective_expiration_date,
    row_number() over (
      partition by app.normalize_code(i.internal_number),
                   app.normalize_ppu(i.ppu),
                   lower(trim(i.result_label)),
                   app.normalize_code(i.guide_number),
                   to_date(trim(i.expiration_text), 'DD-MM-YYYY')
      order by i.source_row
    )                                      as exact_dup_rank
  from tmp_review_history_import i
),
dedup as (
  select *
  from normalized
  where exact_dup_rank = 1
),
mapped as (
  select
    d.source_row,
    d.internal_number,
    d.ppu,
    d.result_code,
    d.guide_number,
    d.effective_expiration_date,
    f.id          as fleet_id,
    f.terminal_id,
    lag(d.effective_expiration_date)
      over (partition by f.id order by d.source_row) as previous_effective_expiration
  from dedup d
  left join public.fleet f
    on f.internal_number = d.internal_number
   and f.ppu = d.ppu
)
select *
from mapped;

do $$
begin
  if exists (
    select 1
    from tmp_review_history_resolved
    where result_code is null
  ) then
    raise exception 'TECH_REVIEW_HISTORY_IMPORT_UNKNOWN_RESULT';
  end if;

  if exists (
    select 1
    from tmp_review_history_resolved
    where guide_number is null
  ) then
    raise exception 'TECH_REVIEW_HISTORY_IMPORT_GUIDE_REQUIRED';
  end if;

  if exists (
    select 1
    from tmp_review_history_resolved
    where effective_expiration_date is null
  ) then
    raise exception 'TECH_REVIEW_HISTORY_IMPORT_INVALID_EXPIRATION_DATE';
  end if;

  if exists (
    select 1
    from tmp_review_history_resolved
    where fleet_id is null or terminal_id is null
  ) then
    raise exception 'TECH_REVIEW_HISTORY_IMPORT_FLEET_NOT_FOUND';
  end if;
end
$$;

create temporary table tmp_review_history_prepared on commit drop as
select
  r.source_row,
  r.internal_number,
  r.ppu,
  r.result_code,
  r.guide_number,
  r.effective_expiration_date,
  r.previous_effective_expiration,
  r.fleet_id,
  r.terminal_id,
  a.actor_id,
  ((r.effective_expiration_date::timestamp at time zone app.local_timezone())
    + interval '12 hours'
    + (r.source_row * interval '1 second')) as synthetic_return_at
from tmp_review_history_resolved r
cross join tmp_review_history_actor a;

insert into app.fleet_legacy_expirations (
  fleet_id,
  expiration_date,
  source_guide_number,
  source_result
)
select
  p.fleet_id,
  coalesce(p.previous_effective_expiration, p.effective_expiration_date),
  p.guide_number,
  'REJECTED_HISTORY_IMPORT'
from tmp_review_history_prepared p
where p.result_code = 'REJECTED'
on conflict (fleet_id) do update
set expiration_date = excluded.expiration_date,
    source_guide_number = excluded.source_guide_number,
    source_result = excluded.source_result,
    updated_at = now();

insert into public.technical_review_events (
  fleet_id,
  terminal_id,
  driver_name,
  departure_at,
  return_at,
  status,
  result,
  guide_number,
  expiration_date,
  previous_expiration_date,
  created_by,
  closed_by,
  created_at,
  updated_at
)
select
  p.fleet_id,
  p.terminal_id,
  'IMPORTACION HISTORICA',
  p.synthetic_return_at - interval '5 minutes',
  p.synthetic_return_at,
  'CLOSED',
  p.result_code,
  p.guide_number,
  case
    when p.result_code = 'APPROVED' then p.effective_expiration_date
    else null
  end,
  case
    when p.result_code = 'APPROVED' then p.previous_effective_expiration
    else coalesce(p.previous_effective_expiration, p.effective_expiration_date)
  end,
  p.actor_id,
  p.actor_id,
  p.synthetic_return_at - interval '5 minutes',
  p.synthetic_return_at
from tmp_review_history_prepared p
where not exists (
  select 1
  from public.technical_review_events e
  where e.fleet_id = p.fleet_id
    and e.result = p.result_code
    and e.guide_number = p.guide_number
    and coalesce(e.expiration_date, e.previous_expiration_date) = p.effective_expiration_date
);
