-- SECCION: REVISION TECNICA
-- =============================================================================
-- 1300 · Technical review history import
-- =============================================================================
-- Source compatibility assessment:
--   - Compatible: internal number, PPU, result, guide number, expiration date.
--   - Missing in source: terminal, departure timestamp, return timestamp.
--   - Missing in source: driver and actor identity.
--
-- Import assumptions:
--   - `terminal_id` is inferred from the current fleet assignment.
--   - `driver_name` uses a legacy placeholder.
--   - `created_by` and `closed_by` use the first active profile available.
--   - Synthetic timestamps are anchored to `VENCIMIENTO`, because the source
--     sheet does not provide `SALIDA` nor `REGRESO`.
--   - Rejected rows are intentionally excluded: without reasons, documents,
--     analysis, timestamps, or actor identity they are not valid operational
--     review events and would display misleading information.
-- =============================================================================

create table if not exists app.fleet_legacy_expirations (
  fleet_id            uuid primary key references public.fleet (id) on delete cascade,
  expiration_date     date not null,
  source_guide_number text,
  source_result       text not null default 'REJECTED_HISTORY_IMPORT',
  updated_at          timestamptz not null default now(),

  constraint fleet_legacy_expirations_source_result_check check (
    source_result in ('REJECTED_HISTORY_IMPORT')
  ),
  constraint fleet_legacy_expirations_guide_check check (
    source_guide_number is null or length(trim(source_guide_number)) between 1 and 60
  )
);

comment on table app.fleet_legacy_expirations is
  'Fallback expiration dates imported from legacy rejected reviews when no approved event exists in the normalized history.';

create or replace function app.legacy_expiration_for_fleet(p_fleet_id uuid)
returns date
language sql
stable
security definer
set search_path = ''
as $$
  select e.expiration_date
  from app.fleet_legacy_expirations e
  where e.fleet_id = p_fleet_id;
$$;

revoke all on function app.legacy_expiration_for_fleet(uuid) from public;
grant execute on function app.legacy_expiration_for_fleet(uuid) to authenticated, service_role;

create or replace view public.fleet_expiration_status
with (security_invoker = on) as
select
  f.id                          as fleet_id,
  f.internal_number,
  f.ppu,
  f.model,
  f.subclass,
  f.fuel_type,
  f.terminal_id,
  f.active,
  la.id                         as last_approved_event_id,
  coalesce(la.expiration_date, app.legacy_expiration_for_fleet(f.id))
                                as expiration_date,
  la.return_at                  as last_approved_at,
  la.guide_number               as last_guide_number,
  case
    when coalesce(la.expiration_date, app.legacy_expiration_for_fleet(f.id)) is null then 'NO_RECORD'
    when coalesce(la.expiration_date, app.legacy_expiration_for_fleet(f.id)) < app.today_local() then 'EXPIRED'
    when coalesce(la.expiration_date, app.legacy_expiration_for_fleet(f.id))
         <= app.today_local() + app.expiring_soon_days() then 'EXPIRING_SOON'
    else 'VALID'
  end                           as expiration_status,
  (coalesce(la.expiration_date, app.legacy_expiration_for_fleet(f.id)) - app.today_local())
                                as days_to_expiration,
  f.zone
from public.fleet f
left join lateral (
  select e.id, e.expiration_date, e.return_at, e.guide_number
  from public.technical_review_events e
  where e.fleet_id = f.id
    and e.status = 'CLOSED'
    and e.result = 'APPROVED'
  order by e.return_at desc, e.created_at desc
  limit 1
) la on true;

